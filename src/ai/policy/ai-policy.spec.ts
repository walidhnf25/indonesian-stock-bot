describe('numeric-grounding helpers', () => {
  it('parses Indonesian and plain number formats with units', () => {
    const t = (s: string) => extractNumberTokens(s).map((x) => [x.values, x.unit]);
    expect(t('Rp6.100')).toEqual([[[6100, 6.1], 'rp']]);
    expect(t('33,5')).toEqual([[[33.5], null]]);
    expect(t('-38.84')[0][0]).toEqual([38.84]);
    expect(t('1,25%')).toEqual([[[1.25], '%']]);
    expect(t('2x')).toEqual([[[2], 'x']]);
    expect(extractNumberTokens('118,04 jt')[0].values).toEqual([118_040_000]);
    expect(extractNumberTokens('1,2 T')[0].values[0]).toBeCloseTo(1.2e12, 0);
  });

  it('is grounded when equal after display rounding, regardless of sign', () => {
    expect(isGrounded(1.23, [1.2345679])).toBe(true);
    expect(isGrounded(1.2, [1.2345679])).toBe(true);
    expect(isGrounded(1, [1.2345679])).toBe(true);
    expect(isGrounded(1.3, [1.2345679])).toBe(false);
    expect(isGrounded(0.65, [-0.6451613])).toBe(true);
    // scaled values (jt/rb/M/T) hide the low digits, so they get a small relative tolerance...
    expect(isGrounded(118_040_000, [118_044_900], { scaled: true })).toBe(true);
    // ...plain numbers do not: Rp3.081 is not Rp3.080
    expect(isGrounded(118_040_000, [118_044_900])).toBe(false);
    expect(isGrounded(3081, [3080])).toBe(false);
  });

  it('exempts small integers unless attached to %, x or a metric word', () => {
    expect(findUngroundedNumbers('Ada 3 risiko dan 2 pengamatan.', [])).toEqual([]);
    expect(findUngroundedNumbers('Naik 7% hari ini.', [])).toEqual(['7%']);
    expect(findUngroundedNumbers('Volume 5x rata-rata.', [])).toEqual(['5x']);
    expect(findUngroundedNumbers('RSI 7 sekarang.', [])).toEqual(['7']);
    // an RSI VALUE after the word RSI is checked, not mistaken for a period label
    expect(findUngroundedNumbers('RSI 12,4 sekarang.', [37.2])).toEqual(['12,4']);
    expect(findUngroundedNumbers('RSI(14) = 37,2 dan MA20 6.340', [37.2, 6340])).toEqual([]);
  });

  it('strips dates, times, durations and indicator labels only', () => {
    const cleaned = stripNonClaims(
      'MA50 dan EMA12, 20 hari, 1 Oktober 2026, 15:59 WIB, 2026-10-01, harga 6.100',
    );
    expect(cleaned).toContain('6.100');
    expect(cleaned).not.toMatch(/MA50|EMA12|20 hari|Oktober|15:59|2026-10-01/);
  });
});

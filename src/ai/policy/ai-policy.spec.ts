describe('AI output policy — data-bound checks', () => {
  const context = {
    quote: { price: 3080, changePercent: -0.65 },
    technical: { trend: 'BEARISH', rsi14: 37.2, ma: { ma20: 3254, ma50: 3140 } },
    facts: [
      'Harga terakhir Rp3.080, turun 0,65% dari penutupan sebelumnya (Rp3.100).',
      'Harga di bawah MA20 (Rp3.254) sebesar 5,35%.',
      'RSI(14) = 37,2, zona netral bawah.',
      'Volume hari ini 118,04 jt lembar = 0,79x rata-rata 20 hari sebelumnya.',
    ],
    foreignFlow: null,
    brokerSummary: null,
  };
  const ctx = buildPolicyContext(context);

  it('accepts text whose numbers all come from the data (rounded/formatted as displayed)', () => {
    const text =
      'Harga turun 0,65% ke Rp3.080, di bawah MA20 (Rp3.254). RSI(14) 37,2 dan volume 118,04 jt, 0,79x rata-rata 20 hari.';
    expect(checkTextPolicy([text], ctx)).toEqual([]);
  });

  it('rejects invented prices, RSI values and percentages', () => {
    expect(categoriesOf('Harga ada di Rp3.500 hari ini.', ctx)).toContain('ungrounded_number');
    expect(categoriesOf('RSI berada di 12,4 sekarang.', ctx)).toContain('ungrounded_number');
    expect(categoriesOf('Harga naik 7% dalam sehari.', ctx)).toContain('ungrounded_number');
    expect(categoriesOf('Volume mencapai 500 jt lembar.', ctx)).toContain('ungrounded_number');
  });

  it('ignores indicator labels, periods and dates (they are not market claims)', () => {
    const text =
      'Harga di bawah MA20 dan MA50; RSI(14) netral; perubahan 20 hari terakhir. Data 3 Oktober 2026, 15:59 WIB.';
    expect(findUngroundedNumbers(text, ctx.allowedNumbers)).toEqual([]);
  });

  it('flags a contradiction between the text and the actual price direction', () => {
    expect(categoriesOf('Harga BBRI naik hari ini.', ctx)).toContain('contradiction');
    expect(categoriesOf('Harga BBRI tidak naik, turun 0,65%.', ctx)).toEqual([]);
    expect(categoriesOf('Harga turun 0,65% setelah sebelumnya naik.', ctx)).toEqual([]);
    const up = buildPolicyContext({ ...context, quote: { price: 3100, changePercent: 1.2 } });
    expect(categoriesOf('Harga saham melemah hari ini.', up)).toContain('contradiction');
  });

  it('flags a trend label that contradicts the computed classification', () => {
    expect(categoriesOf('Tren bullish yang kuat.', ctx)).toContain('contradiction');
    expect(categoriesOf('Tren bearish yang terlihat jelas.', ctx)).toEqual([]);
    expect(categoriesOf('Belum terlihat tren bullish.', ctx)).toEqual([]);
  });

  it('rejects claims about foreign flow / broker data that the application does not have', () => {
    expect(categoriesOf('Investor asing net buy besar hari ini.', ctx)).toContain(
      'unsupported_data_claim',
    );
    expect(categoriesOf('Bandar sedang akumulasi saham ini.', ctx)).toContain(
      'unsupported_data_claim',
    );
    expect(categoriesOf('Data foreign flow tidak tersedia.', ctx)).toEqual([]);
    // when the data really exists, the claim is allowed
    const withFlow = buildPolicyContext({ ...context, foreignFlow: { netForeign: 5 } });
    expect(categoriesOf('Investor asing net buy hari ini.', withFlow)).not.toContain(
      'unsupported_data_claim',
    );
  });

  it('only builds allowed numbers from application data plus definitional RSI constants', () => {
    const allowed = collectAllowedNumbers(context);
    expect(isGrounded(3080, allowed)).toBe(true);
    expect(isGrounded(70, allowed)).toBe(true); // RSI zone constant
    expect(isGrounded(3081.7, allowed)).toBe(false);
  });
});

